package intro;

public class simple_interest {
	
	public static void main(String[] args) {
		
		int p = 10000;  // 10000 principal amount
		
		int r = 10;     // 10% rate
		
		int t = 12;     // 12 months timetaken
		
		int simple_interest = (p * r * t) / 100;
		
		System.out.println(simple_interest);
		
	}

}
