package intro;

public class volume_and_area_of_cylinder {
	
	public static void main(String[] args) {
		
		int r = 8;
		
		int h = 5;
		
		double volume = 3.14 * r * r * h;
		
		double area = (2 * 3.14 * r * h) + ( 2 * 3.14 * r * r);
		
		System.out.println(volume);
		
		System.out.println(area);
		
	}

}
