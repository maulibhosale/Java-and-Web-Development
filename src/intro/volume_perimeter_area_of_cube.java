package intro;

public class volume_perimeter_area_of_cube {
	
	public static void main(String[] args) {
		
		int a = 7;    //a side of cube
		
		double volume = a * a * a ;
		
		double area = 6 * a * a ;
		
		double perimeter = 6 * a;
		
		System.out.println(volume);
		
		System.out.println(area);
		
		System.out.println(perimeter);
		
		
	}

}
